"""Every entry of the roadmap's tool list, and what does it (E1, T7).

The roadmap (`docs/roadmap-v2.md`, Phase 16) lists 447 things a Studio needs,
in 23 families. Each is done here by one of three things:

* a **tool** in the registry (one or more, by name), with the setting that
  does it when the tool does more than one thing;
* a **step**'s setting, given as a config that `test_tool_coverage` runs on a
  sample table, so the setting is shown to work and not only to exist;
* a **feature** of the Studio or of recipes, with the test that exercises it,
  as ``path::test name`` from the repository's root.

`test_tool_coverage` reads the roadmap's list and fails when an entry is
missing here or is here twice, names a tool or step that does not exist, or
names a feature whose test is not where it says. One entry waits on the next
phase and says so: a custom plugin is Phase 23's.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

#: Another dataset a step entry's config may read (a join, a union).
OTHER_DATASET = "00000000-0000-0000-0000-0000000000c0"


@dataclass(frozen=True)
class Done:
    entry: str
    by: str  # "tool", "step", "feature" or "later"
    tools: tuple[str, ...] = ()
    step: str | None = None
    config: dict[str, Any] = field(default_factory=dict)
    how: str = ""
    test: str = ""


def tool(entry: str, *names: str, how: str = "") -> Done:
    return Done(entry, "tool", tools=names, how=how)


def step(entry: str, step_type: str, config: dict[str, Any], how: str = "") -> Done:
    return Done(entry, "step", step=step_type, config=config, how=how)


def feature(entry: str, how: str, test: str) -> Done:
    return Done(entry, "feature", how=how, test=test)


def later(entry: str, how: str) -> Done:
    return Done(entry, "later", how=how)


def _aggregate(entry: str, function: str, **extra: Any) -> Done:
    return step(entry, "aggregate", {"group_by": ["region"], "aggregations": [
        {"column": "amount", "function": function, **extra}]}, how=f"function: {function}")


def _join(entry: str, how: str) -> Done:
    config: dict[str, Any] = {"right_dataset_id": OTHER_DATASET, "how": how}
    if how != "cross":
        config.update(left_on=["id"], right_on=["id"])
    return step(entry, "join_datasets", config, how=f"how: {how}")


