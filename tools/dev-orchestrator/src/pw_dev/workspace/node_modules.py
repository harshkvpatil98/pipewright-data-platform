"""Which `node_modules` directories a checkout has to borrow.

A candidate is a `git worktree`, so it has no installed JavaScript
dependencies at all. The controller links them from the original checkout
rather than running `npm ci` per worktree, which would cost gigabytes and
minutes per run.

Linking only the *root* `node_modules` was not enough, and the way it failed
was quiet. npm hoists what it can to the root, but anything it cannot hoist —
a version a workspace pins differently from its sibling — stays in that
workspace's own `node_modules`. In this repository `@types/node` is one of
them: it lives in `apps/web/node_modules`, so a candidate that borrowed only
the root directory type-checked without it and reported

    error TS2591: Cannot find name 'process'

as though the source were wrong. `web:typecheck`, `web:build`, `web:lint`,
`web:tests` and therefore the `repo:verify` gate all failed on every candidate,
for a reason that had nothing to do with the phase being verified.

The workspaces are read from the root `package.json` rather than guessed, so
this follows the repository's own declaration instead of a scan that might pick
up a nested dependency's own directory.

They are **copied, not linked**. Linking looked obviously right — the tree is
600 MB and identical for every checkout — but Turbopack refuses it:

    FATAL: Symlink [project]/apps/web/node_modules is invalid,
           it points out of the filesystem root

so `next build`, and therefore the `repo:verify` gate, could not pass in any
candidate. On APFS a clone is copy-on-write, which makes 600 MB cost about five
seconds and almost no disk until something writes to it; the fallback is an
ordinary recursive copy, which is slow but still correct. A real directory also
means a check writing a build cache writes inside its own checkout instead of
reaching back into the original through a link, so the copy is better isolation
as well as the only thing that works.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import sys
from pathlib import Path

NODE_MODULES = "node_modules"


def workspace_dirs(repo_root: Path) -> list[str]:
    """The workspace directories the root `package.json` declares.

    A glob like `packages/*` is expanded against the checkout. A malformed or
    absent `package.json` yields nothing extra rather than an exception: the
    root directory alone is still linked, and a JavaScript check that then
    fails says so honestly.
    """
    repo_root = Path(repo_root)
    try:
        document = json.loads((repo_root / "package.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    declared = document.get("workspaces")
    if isinstance(declared, dict):
        declared = declared.get("packages")
    if not isinstance(declared, list):
        return []

    found: list[str] = []
    for entry in declared:
        pattern = str(entry).strip().strip("/")
        if not pattern:
            continue
        if "*" in pattern or "?" in pattern:
            for match in sorted(repo_root.glob(pattern)):
                if match.is_dir():
                    found.append(match.relative_to(repo_root).as_posix())
        elif (repo_root / pattern).is_dir():
            found.append(pattern)
    return found


def node_module_roots(repo_root: Path) -> list[str]:
    """Every `node_modules` a checkout should borrow, root first.

    Only the ones that actually exist. A workspace npm hoisted completely has
    no directory of its own and needs no link.
    """
    repo_root = Path(repo_root)
    roots = [NODE_MODULES]
    for workspace in workspace_dirs(repo_root):
        relative = f"{workspace}/{NODE_MODULES}"
        if (repo_root / relative).is_dir():
            roots.append(relative)
    return [root for root in roots if (repo_root / root).is_dir()]


def provide(repo_root: Path, checkout: Path,
            staging_root: Path | None = None) -> list[str]:
    """Give `checkout` its own copy of every `node_modules` the repository has.

    Returns the relative paths that were provided. A real directory already in
    place is left alone, so a reused checkout keeps the build caches its checks
    wrote.

    A **symlink** is replaced, never preserved — and so is a symlink anywhere in
    the path leading to one. Keeping any of them let the checkout choose where
    a copy landed, or what a later reader followed, and the point of copying is
    that the checkout gets a directory nobody else can reach through.
    """
    repo_root = Path(repo_root)
    checkout = Path(checkout).resolve()
    provided: list[str] = []
    for relative in node_module_roots(repo_root):
        source = repo_root / relative
        target = checkout / relative
        _require_real_ancestry(checkout, target)
        if target.is_symlink():
            target.unlink()
        elif target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        _copy_tree(source, target, staging_root)
        provided.append(relative)
    return provided


def _require_real_ancestry(checkout: Path, target: Path) -> None:
    """Refuse to write anywhere but inside the checkout, and never through a link.

    Containment is decided canonically, and `..` is rejected before the
    filesystem is touched at all. A lexical check was not enough on its own: a
    path spelled `<checkout>/../elsewhere/node_modules` keeps `checkout` among
    its `parents` while resolving outside it, and a probe confirmed such a
    target was accepted.
    """
    checkout = checkout.resolve()
    if any(part == ".." for part in target.parts):
        raise NodeModulesUnsafe(
            f"{target} climbs out of its own path with '..'; a dependency tree "
            f"is named relative to the checkout, not relative to its parent."
        )
    try:
        resolved_parent = target.parent.resolve()
        resolved_parent.relative_to(checkout)
    except (OSError, ValueError):
        raise NodeModulesUnsafe(
            f"{target} does not resolve inside {checkout}; a dependency tree is "
            f"written into the checkout that asked for it and nowhere else."
        ) from None

    current = target.parent
    while True:
        if current.is_symlink():
            raise NodeModulesUnsafe(
                f"{current} is a symlink, and a dependency tree is not written "
                f"through one. Remove it and let the checkout own its own path."
            )
        if current == checkout or current == current.parent:
            break
        current = current.parent


class NodeModulesUnsafe(RuntimeError):
    """The path a dependency tree would be written to cannot be trusted."""


def _copy_tree(source: Path, target: Path,
               staging_root: Path | None = None) -> None:
    """Copy a dependency tree, cheaply where the filesystem allows it.

    `cp -c` on macOS and `--reflink=auto` on Linux ask the filesystem to share
    the blocks until one side is written to. Where that is unavailable the copy
    is real; it is slower, and it is still a directory rather than a link,
    which is the part that matters.

    The copy lands in a staging directory this call creates exclusively, and is
    renamed into place only once it is complete. Exclusively, because a
    predictable name inside the checkout is a name the checkout can occupy
    first: a symlink left there would have been handed to `cp` as the
    destination, followed, and then renamed into place as the dependency tree.
    A tree interrupted halfway is also removed rather than left looking finished
    to the next caller.
    """
    # Held for the whole copy. Creating an exclusive directory and then
    # removing it left the *name* unowned while `cp` ran, which is the window a
    # surviving candidate process needed to put a symlink there.
    # Staged where the checkout cannot reach it. A holder inside the checkout
    # was exclusive when created and still replaceable afterwards: a surviving
    # process could remove it and leave a symlink at that name, and the copy
    # then went through the link with the controller's privileges. `staging_root`
    # is controller-owned run state; the fallback keeps the old behaviour for
    # callers that have none, which is better than refusing to work at all.
    staging_parent = Path(staging_root) if staging_root is not None else target.parent
    staging_parent.mkdir(parents=True, exist_ok=True)
    holder = Path(tempfile.mkdtemp(prefix=f"{target.name}.staging-",
                                   dir=staging_parent))
    staging = holder / "tree"
    try:
        if not _clone(source, staging):
            _remove(staging)
            shutil.copytree(source, staging, symlinks=True, dirs_exist_ok=False)
        if staging.is_symlink() or not staging.is_dir():
            raise NodeModulesUnsafe(
                f"the staged copy at {staging} is not a directory; refusing to "
                f"install it as a dependency tree"
            )
        os.replace(staging, target)
    finally:
        _remove(holder)


def _remove(path: Path) -> None:
    """Delete whatever is there, link or directory. `rmtree` will not unlink."""
    if path.is_symlink() or path.is_file():
        path.unlink(missing_ok=True)
    elif path.exists():
        shutil.rmtree(path, ignore_errors=True)


def _clone(source: Path, target: Path) -> bool:
    """Ask the filesystem for a copy-on-write copy. False if it declined."""
    if sys.platform == "darwin":
        argv = ["cp", "-Rc", str(source), str(target)]
    elif sys.platform.startswith("linux"):
        argv = ["cp", "-R", "--reflink=auto", str(source), str(target)]
    else:
        return False
    try:
        result = subprocess.run(  # noqa: S603 - fixed argv
            argv, capture_output=True, text=True, timeout=1800, check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0 and target.exists()
