"""A checkout needs the dependencies npm did not hoist, and needs them real.

Two defects, found by running the checks against a real candidate rather than
by reading the code, and either one alone stopped a run from completing:

* only the root `node_modules` was provided. npm hoists what it can, and what it
  cannot stays in the workspace that pinned it — `@types/node` lives in
  `apps/web/node_modules` here. A candidate without it failed `web:typecheck`
  with `Cannot find name 'process'`, which reads as a defect in the phase's
  source rather than a defect in the checkout;

* they were provided as symlinks, and Turbopack refuses one that leaves the
  project root: `Symlink [project]/apps/web/node_modules is invalid`. So
  `web:build` — and therefore `repo:verify`, a gate — could not pass in any
  candidate, and no run could reach COMMIT.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from pw_dev.workspace import node_modules


def _repo(root: Path, workspaces: list[str] | dict) -> Path:
    (root / "node_modules").mkdir(parents=True)
    (root / "package.json").write_text(
        json.dumps({"name": "root", "workspaces": workspaces}), encoding="utf-8")
    return root


def test_every_workspace_that_kept_its_own_dependencies_is_found(tmp_path: Path):
    repo = _repo(tmp_path / "repo", ["apps/web", "packages/config"])
    (repo / "apps" / "web" / "node_modules" / "@types").mkdir(parents=True)
    (repo / "packages" / "config" / "node_modules").mkdir(parents=True)

    assert node_modules.node_module_roots(repo) == [
        "node_modules", "apps/web/node_modules", "packages/config/node_modules",
    ]


def test_a_fully_hoisted_workspace_needs_nothing_of_its_own(tmp_path: Path):
    repo = _repo(tmp_path / "repo", ["apps/web", "packages/hoisted"])
    (repo / "apps" / "web" / "node_modules").mkdir(parents=True)
    (repo / "packages" / "hoisted").mkdir(parents=True)

    roots = node_modules.node_module_roots(repo)
    assert "packages/hoisted/node_modules" not in roots
    assert roots == ["node_modules", "apps/web/node_modules"]


def test_a_workspace_glob_is_expanded(tmp_path: Path):
    repo = _repo(tmp_path / "repo", ["packages/*"])
    for name in ("alpha", "beta"):
        (repo / "packages" / name / "node_modules").mkdir(parents=True)

    assert node_modules.node_module_roots(repo) == [
        "node_modules", "packages/alpha/node_modules", "packages/beta/node_modules",
    ]


def test_the_object_form_of_the_workspaces_field_is_understood(tmp_path: Path):
    repo = _repo(tmp_path / "repo", {"packages": ["apps/web"]})
    (repo / "apps" / "web" / "node_modules").mkdir(parents=True)
    assert "apps/web/node_modules" in node_modules.node_module_roots(repo)


def test_a_package_json_that_cannot_be_read_still_yields_the_root(tmp_path: Path):
    """A JavaScript check then fails honestly, rather than this raising here."""
    repo = tmp_path / "repo"
    (repo / "node_modules").mkdir(parents=True)
    (repo / "package.json").write_text("{not json", encoding="utf-8")
    assert node_modules.node_module_roots(repo) == ["node_modules"]
    assert node_modules.workspace_dirs(repo) == []


def test_what_a_checkout_receives_is_a_directory_and_not_a_link(tmp_path: Path):
    """The whole point of the second fix: Turbopack rejects the link."""
    repo = _repo(tmp_path / "repo", ["apps/web"])
    (repo / "node_modules" / "left-pad").mkdir(parents=True)
    (repo / "apps" / "web" / "node_modules" / "@types").mkdir(parents=True)

    checkout = tmp_path / "candidate"
    checkout.mkdir()
    provided = node_modules.provide(repo, checkout)

    assert provided == ["node_modules", "apps/web/node_modules"]
    for relative in provided:
        target = checkout / relative
        assert target.is_dir()
        assert not target.is_symlink(), (
            f"{relative} must be a real directory; Turbopack refuses a symlink "
            f"that points out of the project root"
        )
    assert (checkout / "node_modules" / "left-pad").is_dir()
    assert (checkout / "apps" / "web" / "node_modules" / "@types").is_dir()


def test_providing_twice_leaves_an_existing_tree_alone(tmp_path: Path):
    repo = _repo(tmp_path / "repo", [])
    (repo / "node_modules" / "pkg").mkdir(parents=True)
    checkout = tmp_path / "candidate"
    checkout.mkdir()

    assert node_modules.provide(repo, checkout) == ["node_modules"]
    marker = checkout / "node_modules" / "left-by-a-check"
    marker.write_text("build cache", encoding="utf-8")

    assert node_modules.provide(repo, checkout) == []
    assert marker.exists(), "a second call must not discard what a check wrote"


def test_a_copy_is_independent_of_the_original(tmp_path: Path):
    """A clone shares blocks until written to. Writing must not reach back."""
    repo = _repo(tmp_path / "repo", [])
    (repo / "node_modules" / "pkg").mkdir(parents=True)
    (repo / "node_modules" / "pkg" / "index.js").write_text("original\n", encoding="utf-8")

    checkout = tmp_path / "candidate"
    checkout.mkdir()
    node_modules.provide(repo, checkout)

    (checkout / "node_modules" / "pkg" / "index.js").write_text("changed\n", encoding="utf-8")
    assert (repo / "node_modules" / "pkg" / "index.js").read_text(
        encoding="utf-8") == "original\n"


def test_an_interrupted_copy_does_not_leave_a_tree_that_looks_finished(
        tmp_path: Path, monkeypatch):
    """A half-copied tree is indistinguishable from a complete one afterwards.

    `provide()` skips a target that already exists, so a failure partway through
    used to leave packages missing and be skipped on every later call -- failing
    somewhere unrelated and looking like a defect in the code under test.
    """
    repo = _repo(tmp_path / "repo", [])
    (repo / "node_modules" / "pkg").mkdir(parents=True)
    checkout = tmp_path / "candidate"
    checkout.mkdir()

    def explode(*args, **kwargs):
        # Leave debris behind, the way a real interruption would.
        staging = Path(args[1])
        staging.mkdir(parents=True, exist_ok=True)
        (staging / "half").write_text("partial", encoding="utf-8")
        raise OSError("disk full")

    monkeypatch.setattr(node_modules, "_clone", lambda *a, **k: False)
    monkeypatch.setattr(node_modules.shutil, "copytree", explode)

    with pytest.raises(OSError):
        node_modules.provide(repo, checkout)

    assert not (checkout / "node_modules").exists(), (
        "a failed copy must leave nothing a later call would accept"
    )
    assert not list(checkout.glob("node_modules.incoming-*")), "staging is removed"


def test_a_symlink_where_a_dependency_tree_belongs_is_replaced(tmp_path: Path):
    """Keeping it let a checkout choose what the boundary would grant."""
    repo = _repo(tmp_path / "repo", [])
    (repo / "node_modules" / "pkg").mkdir(parents=True)
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()

    checkout = tmp_path / "candidate"
    checkout.mkdir()
    (checkout / "node_modules").symlink_to(elsewhere)

    assert node_modules.provide(repo, checkout) == ["node_modules"]
    assert not (checkout / "node_modules").is_symlink()
    assert (checkout / "node_modules" / "pkg").is_dir()
